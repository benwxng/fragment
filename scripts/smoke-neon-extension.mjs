import assert from 'node:assert/strict';
import {execFileSync} from 'node:child_process';
import {readFile,mkdtemp,rm} from 'node:fs/promises';
import {tmpdir} from 'node:os';
import {resolve,join} from 'node:path';
import {randomUUID} from 'node:crypto';
import {chromium} from 'playwright';
import {S3Client,GetObjectCommand} from '@aws-sdk/client-s3';
import pg from 'pg';
const site=process.env.SMOKE_SITE_URL ?? 'http://localhost:3100';
assert.equal(process.env.NEON_BRANCH,'migration-neon','Run extension verification against the disposable migration branch.');
execFileSync('pnpm',['--filter','@refer/extension','build'],{env:{...process.env,WXT_NEON_API_URL:process.env.NEON_FUNCTION_API_BASE_URL,WXT_SITE_URL:site},stdio:'inherit'});
const extensionPath=resolve('apps/extension/.output/chrome-mv3');
const profile=await mkdtemp(join(tmpdir(),'refer-neon-extension-'));
const [user]=JSON.parse(await readFile('output/migration/smoke-users.json','utf8'));
const exported=JSON.parse(await readFile('output/migration/supabase-export.json','utf8'));
const source=exported.captures[0];
const reference=structuredClone(source.snapshot);reference.id=randomUUID();reference.capturedAt=new Date().toISOString();
const s3=new S3Client({forcePathStyle:true});const object=await s3.send(new GetObjectCommand({Bucket:'uploads',Key:source.screenshot_path}));
reference.screenshot.dataUrl=`data:image/webp;base64,${Buffer.from(await object.Body.transformToByteArray()).toString('base64')}`;reference.screenshot.storagePath=null;
const db=new pg.Client({connectionString:process.env.DATABASE_URL_UNPOOLED});await db.connect();
let context;
try{
 context=await chromium.launchPersistentContext(profile,{channel:'chromium',headless:true,args:[`--disable-extensions-except=${extensionPath}`,`--load-extension=${extensionPath}`]});
 let [worker]=context.serviceWorkers();worker??=await context.waitForEvent('serviceworker');
 const id=new URL(worker.url()).host;
 const web=await context.newPage();await web.goto(`${site}/login`);
 await web.getByRole('textbox',{name:'Email',exact:true}).fill(user.email);
 await web.getByRole('textbox',{name:'Password',exact:true}).fill(user.password);
 await web.getByRole('button',{name:'Sign in',exact:true}).click();await web.waitForURL('**/library');
 const library=await context.newPage();await library.goto(`chrome-extension://${id}/library.html`);
 await library.locator('#account-button').click();
 const authPagePromise=context.waitForEvent('page');
 await library.locator('#sign-in-button').click();
 const authPage=await authPagePromise;
 await authPage.getByRole('button',{name:'Connect extension'}).click();
 await library.locator('#signed-in-panel').waitFor({state:'visible',timeout:30000});
 assert.equal((await library.locator('#signed-in-email').innerText()).trim(),user.email);
 console.log('PASS real extension identity popup and website approval');
 const saved=await library.evaluate(reference=>chrome.runtime.sendMessage({type:'save-reference',reference}),reference);
 assert(saved.ok,JSON.stringify(saved));
 let state;
 for(let attempt=0;attempt<10;attempt++){
  state=await library.evaluate(()=>chrome.runtime.sendMessage({type:'sync-now'}));
  assert(state.ok,JSON.stringify(state));
  if(!state.cloudState.pending)break;
  await new Promise(r=>setTimeout(r,300));
 }
 assert.equal(state.cloudState.pending,0,JSON.stringify(state));
 const row=(await db.query('select * from captures where id=$1',[reference.id])).rows[0];
 assert(row?.screenshot_path);
 const uploaded=await s3.send(new GetObjectCommand({Bucket:'uploads',Key:row.screenshot_path}));
 assert((await uploaded.Body.transformToByteArray()).length>0);
 console.log('PASS extension capture queue, Neon row and screenshot upload');
 await library.reload();
 const restored=await library.evaluate(()=>chrome.runtime.sendMessage({type:'get-cloud-state'}));
 assert.equal(restored.cloudState.authStatus,'signed-in');
 await web.reload();await web.getByRole('link',{name:new RegExp(`View ${source.element_label.replace(/[.*+?^${}()|[\]\\]/g,'\\$&')}`)}).first().waitFor();
 const deleted=await library.evaluate(id=>chrome.runtime.sendMessage({type:'delete-reference',id}),reference.id);assert(deleted.ok);
 await library.evaluate(()=>chrome.runtime.sendMessage({type:'sync-now'}));
 assert.equal((await db.query('select id from captures where id=$1',[reference.id])).rowCount,0);
 await library.evaluate(()=>chrome.runtime.sendMessage({type:'cloud-sign-out'}));
 const signedOut=await library.evaluate(()=>chrome.runtime.sendMessage({type:'get-cloud-state'}));assert.equal(signedOut.cloudState.authStatus,'signed-out');
 console.log('PASS extension session reload, library display, delete sync and signout');
}finally{
 if(context)await context.close();
 await db.query('delete from captures where id=$1',[reference.id]);await db.end();
 await rm(profile,{recursive:true,force:true});
}
